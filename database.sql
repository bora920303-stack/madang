-- 온라인 서점용 Supabase 데이터베이스 구성 SQL
-- 새 Supabase 프로젝트의 SQL Editor에서 한 번 실행합니다.

BEGIN;

-- 도서 목록을 저장합니다.
CREATE TABLE public.books (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  author text NOT NULL,
  price integer NOT NULL CHECK (price >= 0)
);

-- 구매 당시의 도서명과 가격을 함께 보관하는 주문 테이블입니다.
CREATE TABLE public.orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id),
  book_id bigint NOT NULL REFERENCES public.books(id),
  book_title text NOT NULL,
  quantity integer NOT NULL CHECK (quantity BETWEEN 1 AND 10),
  unit_price integer NOT NULL CHECK (unit_price >= 0),
  created_at timestamptz NOT NULL DEFAULT now()
);

-- 내 주문 조회를 빠르게 하기 위한 인덱스입니다.
CREATE INDEX orders_user_id_index ON public.orders (user_id);

