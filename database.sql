-- 웹 역할에 남아 있을 수 있는 기본 테이블 권한을 먼저 제거합니다.
REVOKE ALL PRIVILEGES ON SCHEMA public FROM anon, authenticated;
REVOKE ALL PRIVILEGES ON TABLE public.books FROM anon, authenticated;
REVOKE ALL PRIVILEGES ON TABLE public.orders FROM anon, authenticated;

-- 웹에서 public 스키마와 필요한 조회 기능만 사용할 수 있게 합니다.
GRANT USAGE ON SCHEMA public TO anon, authenticated;
GRANT SELECT ON TABLE public.books TO anon, authenticated;
GRANT SELECT ON TABLE public.orders TO authenticated;

-- 행 단위 보안을 켭니다.
ALTER TABLE public.books ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;

-- 도서는 로그인 여부와 관계없이 조회만 허용합니다.
CREATE POLICY "books_select_for_web"
ON public.books
FOR SELECT
TO anon, authenticated
USING (true);

-- 주문은 로그인한 사용자가 자신의 주문만 조회할 수 있습니다.
CREATE POLICY "orders_select_own"
ON public.orders
FOR SELECT
TO authenticated
USING (auth.uid() = user_id);

-- 웹에서는 이 함수로만 주문을 생성합니다.
CREATE OR REPLACE FUNCTION public.purchase_book(
  p_book_id bigint,
  p_quantity integer
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  current_user_id uuid;
  selected_book public.books%ROWTYPE;
  new_order_id bigint;
BEGIN
  -- 로그인한 사용자만 구매할 수 있습니다.
  current_user_id := auth.uid();
  IF current_user_id IS NULL THEN
    RAISE EXCEPTION '로그인이 필요한 기능입니다.';
  END IF;

  -- 수량은 반드시 1~10 사이의 정수여야 합니다.
  IF p_quantity IS NULL OR p_quantity < 1 OR p_quantity > 10 THEN
    RAISE EXCEPTION '수량은 1부터 10 사이여야 합니다.';
  END IF;

  -- 도서의 현재 제목과 가격은 서버에서 직접 읽습니다.
  SELECT * INTO selected_book
  FROM public.books
  WHERE id = p_book_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION '존재하지 않는 도서입니다.';
  END IF;

  INSERT INTO public.orders (user_id, book_id, book_title, quantity, unit_price)
  VALUES (
    current_user_id,
    selected_book.id,
    selected_book.title,
    p_quantity,
    selected_book.price
  )
  RETURNING id INTO new_order_id;

  RETURN new_order_id;
END;
$$;

-- 함수 실행 권한은 로그인한 사용자에게만 부여합니다.
REVOKE ALL ON FUNCTION public.purchase_book(bigint, integer)
FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.purchase_book(bigint, integer) TO authenticated;

COMMIT;
